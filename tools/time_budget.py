#!/usr/bin/env python3
"""Chapter-by-chapter time budget, computed from the shipped chapter data.

This is a MODEL, not a measurement. It turns countable content (dialogue length, document words,
floor area, puzzle gates, encounters) into a low/high estimate for a first-time player using the
explicit rates below. Replace the rates with real numbers once human playtests exist.
Usage: python3 tools/time_budget.py <story_export.json> docs/17_TIME_BUDGET.md
"""
import json, sys
src, out = sys.argv[1], sys.argv[2]
D = json.load(open(src))

# Optional content (not needed to finish the chapter), by chapter number -> legend keys.
OPTIONAL = {
    1: "WQuqfe", 2: "KqUnj8", 3: "XJNUQm", 4: "GxnrU8BfTh", 5: "cObnxmQyU", 6: "WgbkT8", 7: "NwQjT",
    8: "sYhijltyOzABE8mTfpn", 9: "OaTkQ", 10: "NhrTb8", 11: "YhQTsBGjJW", 12: "wh8", 13: "P",
}
# Rates (seconds unless noted) — first-time player, cautious stealth pace.
RATE = {
    "explore_low": 0.55, "explore_high": 1.3,       # per m2 of walkable floor (includes looking around, backtracking)
    "puzzle_low": 75, "puzzle_high": 210,            # per gated puzzle (code, order, alignment, physics, key)
    "enc_low": 45, "enc_high": 150,                  # per authored Listener encounter (hide, wait, reroute)
    "retry": 0.15,                                   # deaths/reloads added to the high estimate
    "read_wpm": 200,                                 # document reading speed
}

def line_secs(e):
    return e[2] if len(e) > 2 and isinstance(e[2], (int, float)) else min(9, max(2, 1.4 + len(e[1]) * 0.058))

def walk(evs, acc):
    for e in evs or []:
        if not isinstance(e, list) or not e: continue
        c = str(e[0])
        if (c == "" or c != c.lower()) and len(e) > 1 and isinstance(e[1], str): acc["say"] += line_secs(e)
        elif c == "wait": acc["say"] += float(e[1])
        elif c == "cam" and len(e) > 3: acc["say"] += float(e[3])
        elif c == "listener" and e[1] in ("spawn", "seek", "ambush", "hunt", "stalk"): acc["enc"] += 1
        elif c in ("if", "ifnot"):
            walk(e[2], acc); walk(e[3] if len(e) > 3 else [], acc)
        elif c == "choice":
            for o in e[2]: walk(o[1], acc)

def is_puzzle(l):
    t = l.get("t")
    return (t == "door" and ("code" in l or "lock" in l or "needflag" in l)) or \
           (t == "use" and any(k in l for k in ("seq", "cycle", "code", "need", "if"))) or t == "plate"

rows = []
for ch in D["chapters"]:
    if "ending" in ch or ch["n"] == 0: continue
    n = ch["n"]; opt = set(OPTIONAL.get(n, ""))
    part = {"main": {"say": 0.0, "enc": 0, "read": 0.0, "puz": 0}, "opt": {"say": 0.0, "enc": 0, "read": 0.0, "puz": 0}}
    walk(ch.get("start_ev"), part["main"]); walk(ch.get("pre_ev"), part["main"])
    for g in ch.get("groups", {}).values(): walk(g, part["main"])
    part["main"]["enc"] += len(ch.get("ai", []))
    seq_seen, cyc_seen = set(), set()
    for k, l in ch["leg"].items():
        side = part["opt" if k in opt else "main"]
        if l.get("ngp"): continue                      # New Game+ content is budgeted separately
        walk(l.get("ev"), side); walk(l.get("lines"), side)
        if l.get("t") == "note": side["read"] += len(l.get("text", "").split()) / RATE["read_wpm"] * 60
        if is_puzzle(l):
            if "seq" in l:
                if l["seq"] in seq_seen: continue
                seq_seen.add(l["seq"])
            if "cycle" in l:
                if l["group"] in cyc_seen: continue
                cyc_seen.add(l["group"])
            side["puz"] += 1
    floor = sum(1 for r in ch["map"] for c in r if c not in "# ") * 4
    rows.append((n, ch["title"], floor, part))

def est(p, floor_share, lo):
    r = RATE
    base = p["say"] + p["read"] + floor_share * (r["explore_low"] if lo else r["explore_high"]) \
         + p["puz"] * (r["puzzle_low"] if lo else r["puzzle_high"]) + p["enc"] * (r["enc_low"] if lo else r["enc_high"])
    return base / 60 * (1 if lo else 1 + r["retry"])

w = ["# DEAD FREQUENCY — Campaign Time Budget\n",
     "**This is a model, not a measurement.** It is generated by `tools/time_budget.py` from the shipped chapter data: dialogue and camera time, document words, walkable floor area, puzzle gates and authored Listener encounters, converted to minutes with the explicit rates below. No human has played the full campaign yet; the first playtest round (13_TESTING_PLAN.md) replaces these rates with measured ones. **Do not quote the 10–15 h target as achieved until playtests show it.**\n",
     "Rates: exploration %.2f–%.2f s per m² of floor · puzzle %d–%d s each · authored encounter %d–%d s each · reading %d wpm · +%d%% retries on the high estimate. Optional areas are assigned %s of their floor area." % (
         RATE["explore_low"], RATE["explore_high"], RATE["puzzle_low"], RATE["puzzle_high"], RATE["enc_low"], RATE["enc_high"], RATE["read_wpm"], RATE["retry"] * 100, "30%"),
     "", "| Ch | Title | Floor m² | Dialogue & camera (min) | Reading (min) | Puzzles main/opt | Encounters main/opt | Main path (min) | Optional (min) |",
     "|---|---|---|---|---|---|---|---|---|"]
T = {"mlo": 0, "mhi": 0, "olo": 0, "ohi": 0}
for n, title, floor, p in rows:
    m, o = p["main"], p["opt"]
    mlo, mhi = est(m, floor * 0.7, True), est(m, floor * 0.7, False)
    olo, ohi = est(o, floor * 0.3, True), est(o, floor * 0.3, False)
    T["mlo"] += mlo; T["mhi"] += mhi; T["olo"] += olo; T["ohi"] += ohi
    w.append("| %02d | %s | %d | %.0f | %.0f | %d / %d | %d / %d | %.0f–%.0f | %.0f–%.0f |" % (
        n, title, floor, (m["say"] + o["say"]) / 60, (m["read"] + o["read"]) / 60, m["puz"], o["puz"], m["enc"], o["enc"], mlo, mhi, olo, ohi))
pro = 135 / 60; endc = 4.0
w.append("")
w.append("Prologue cinematic: %.1f min (measured, `tools/test.sh introtime`). Ending + credits: ≈ %.0f min." % (pro, endc))
w.append("")
w.append("| Total (model) | Low | High |\n|---|---|---|")
w.append("| Main path only | %.1f h | %.1f h |" % ((T["mlo"] + pro + endc) / 60, (T["mhi"] + pro + endc) / 60))
w.append("| Main path + all optional content | %.1f h | %.1f h |" % ((T["mlo"] + T["olo"] + pro + endc) / 60, (T["mhi"] + T["ohi"] + pro + endc) / 60))
w.append("")
w.append("New Game+ adds the 88.0 thread, changed encounters and a smarter Listener; it is replay content and is not counted above.")
w.append("")
w.append("## How to replace the model with data\n1. Playtest build logs chapter start/end times (planned: a debug overlay writes `playtime.csv`).\n2. Five first-time players per round; record main-path time, optional time, deaths.\n3. Update `RATE` in `tools/time_budget.py` so the model reproduces the measured median, then use it to plan further content.")
open(out, "w").write("\n".join(w) + "\n")
print("main %.1f–%.1f h, with optional %.1f–%.1f h" % ((T["mlo"] + pro + endc) / 60, (T["mhi"] + pro + endc) / 60, (T["mlo"] + T["olo"] + pro + endc) / 60, (T["mhi"] + T["ohi"] + pro + endc) / 60))
